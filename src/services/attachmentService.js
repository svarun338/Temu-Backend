import { config } from '../config/index.js';
import { attachmentRepository } from '../repositories/attachmentRepository.js';
import { conversationRepository } from '../repositories/conversationRepository.js';
import { AppError } from '../utils/AppError.js';
import { detectFileType, INLINE_MIME_TYPES, sanitizeFileName } from '../utils/fileType.js';
import { logger } from '../utils/logger.js';
import { attachmentStorage } from './attachmentStorage.js';
import { conversationService } from './conversationService.js';
import { messageService } from './messageService.js';
import { toAttachment } from './serializers.js';

const notFound = () => AppError.notFound('File not found');
const megabytes = (bytes) => Math.round(bytes / (1024 * 1024));
const sizeLabel = (bytes) => (bytes < 1024 * 1024 ? `${Math.round(bytes / 1024)} KB` : `${megabytes(bytes)} MB`);
// Previews are generated by the client as JPEG and served as image/jpeg.
const THUMBNAIL_TYPES = new Set(['image/jpeg']);
export const STICKER_TYPES = new Set(['image/png', 'image/webp', 'image/gif']);
const ENCRYPTED_KINDS = new Set(['image', 'video', 'audio', 'voice', 'file']);
const GCM_OVERHEAD = 16; // AES-GCM authentication tag

export const attachmentService = {
  /**
   * Store an uploaded file for a conversation the user may post in.
   * `kindHint`: 'voice' (recorded voice note), 'file' (send as document, e.g. an
   * uncompressed photo) or undefined (decide from the content).
   * Temp files are always removed, whether the upload is accepted or not.
   */
  async upload(userId, { conversationId, file, thumbnail, kindHint, width, height, durationMs, pageCount, encrypted }) {
    try {
      if (!file) throw AppError.badRequest('Choose a file to send');
      await messageService.assertCanPost(userId, conversationId);
      if (encrypted === 'true') return await this.storeEncrypted(userId, { conversationId, file, thumbnail, kind: kindHint });

      const head = await attachmentStorage.readHead(file.path);
      const wantsAudio = kindHint === 'voice' || kindHint === 'audio';
      const detected = detectFileType(head, file.originalname, { wantsAudio });
      if (detected.blocked) throw new AppError(415, 'BLOCKED_FILE_TYPE', detected.blocked);

      let kind = detected.kind;
      if (kindHint === 'sticker') {
        if (!STICKER_TYPES.has(detected.mime)) throw new AppError(415, 'UNSUPPORTED_FILE', 'Stickers must be PNG, WebP or GIF images');
        kind = 'sticker';
      } else if (kindHint === 'file') kind = 'file';
      else if (kindHint === 'voice') {
        if (detected.kind !== 'audio') throw new AppError(415, 'UNSUPPORTED_FILE', 'Voice messages must be audio recordings');
        kind = 'voice';
      }

      const limit = config.uploads.maxBytes[kind];
      if (file.size > limit) {
        throw new AppError(413, 'FILE_TOO_LARGE', `This ${kind === 'file' ? 'file' : kind} is too large (max ${sizeLabel(limit)})`);
      }
      if (file.size === 0) throw AppError.badRequest('The file is empty');
      const used = await attachmentRepository.uploadedBytesSince(userId, new Date(Date.now() - 24 * 3_600_000));
      if (used + file.size > config.uploads.dailyQuotaBytes) {
        throw new AppError(413, 'UPLOAD_QUOTA_EXCEEDED', `You can upload up to ${megabytes(config.uploads.dailyQuotaBytes)} MB per day. Please try again later.`);
      }

      // PDFs get a first-page preview (rendered in the sender's browser) and a page count.
      const pdf = detected.mime === 'application/pdf';
      let thumbnailKey = null;
      if (thumbnail && (kind === 'video' || kind === 'image' || pdf)) {
        const thumbType = detectFileType(await attachmentStorage.readHead(thumbnail.path), 'thumbnail');
        if (!THUMBNAIL_TYPES.has(thumbType.mime) || thumbnail.size > config.uploads.thumbnailMaxBytes) {
          throw new AppError(415, 'UNSUPPORTED_FILE', 'Invalid preview image');
        }
        thumbnailKey = await attachmentStorage.store(thumbnail.path, 'image/jpeg');
      }

      const storageKey = await attachmentStorage.store(file.path, detected.mime);
      const media = kind === 'image' || kind === 'video' || kind === 'sticker' || (pdf && Boolean(thumbnailKey));
      const timed = kind === 'video' || kind === 'audio' || kind === 'voice';
      const id = await attachmentRepository.insert({
        uploaderId: userId,
        conversationId,
        kind,
        mimeType: detected.mime,
        originalName: sanitizeFileName(file.originalname, kind === 'voice' ? 'voice-message' : 'file'),
        sizeBytes: file.size,
        storageKey,
        thumbnailKey,
        width: media ? width : null,
        height: media ? height : null,
        durationMs: timed ? durationMs : null,
        pageCount: pdf ? pageCount : null,
      });
      return toAttachment(await attachmentRepository.findById(id));
    } finally {
      await attachmentStorage.discardTemp(file?.path);
      await attachmentStorage.discardTemp(thumbnail?.path);
    }
  },

  /**
   * An end-to-end encrypted upload: opaque bytes the server can't inspect. Only the
   * size is checked (per declared kind); name, type, dimensions and the file key travel
   * inside the encrypted message. A preview image, if any, is encrypted the same way.
   */
  async storeEncrypted(userId, { conversationId, file, thumbnail, kind }) {
    if (!ENCRYPTED_KINDS.has(kind)) throw AppError.badRequest('Say what kind of file this is');
    const limit = config.uploads.maxBytes[kind] + GCM_OVERHEAD;
    if (file.size > limit) throw new AppError(413, 'FILE_TOO_LARGE', `This ${kind} is too large (max ${sizeLabel(limit - GCM_OVERHEAD)})`);
    if (file.size <= GCM_OVERHEAD) throw AppError.badRequest('The file is empty');
    const used = await attachmentRepository.uploadedBytesSince(userId, new Date(Date.now() - 24 * 3_600_000));
    if (used + file.size > config.uploads.dailyQuotaBytes) {
      throw new AppError(413, 'UPLOAD_QUOTA_EXCEEDED', `You can upload up to ${megabytes(config.uploads.dailyQuotaBytes)} MB per day. Please try again later.`);
    }
    let thumbnailKey = null;
    if (thumbnail && kind !== 'voice' && kind !== 'audio') {
      if (thumbnail.size > config.uploads.thumbnailMaxBytes + GCM_OVERHEAD) throw new AppError(415, 'UNSUPPORTED_FILE', 'Invalid preview image');
      thumbnailKey = await attachmentStorage.store(thumbnail.path);
    }
    const storageKey = await attachmentStorage.store(file.path);
    const id = await attachmentRepository.insert({
      uploaderId: userId,
      conversationId,
      kind,
      mimeType: 'application/octet-stream',
      originalName: 'encrypted',
      sizeBytes: file.size,
      storageKey,
      thumbnailKey,
      encrypted: true,
    });
    return toAttachment(await attachmentRepository.findById(id));
  },

  /**
   * An attachment the user may download: unsent uploads only by their uploader,
   * sent ones by participants of the conversation. Everyone else gets 404.
   */
  async getForDownload(userId, attachmentId, { thumbnail = false } = {}) {
    const row = await attachmentRepository.findById(attachmentId);
    if (!row) throw notFound();
    const allowed = row.message_id
      ? await conversationRepository.isParticipant(row.conversation_id, userId)
      : row.uploader_id === userId;
    if (!allowed) throw notFound();
    if (thumbnail && !row.thumbnail_key) throw notFound();

    const key = thumbnail ? row.thumbnail_key : row.storage_key;
    if (Number(row.encrypted)) {
      // Ciphertext: always a download; the app decrypts it on the device.
      return { storageKey: key, mimeType: 'application/octet-stream', name: 'encrypted', inline: false };
    }
    const mimeType = thumbnail ? 'image/jpeg' : row.mime_type;
    return {
      storageKey: key,
      mimeType,
      name: thumbnail ? 'thumbnail.jpg' : row.original_name,
      inline: thumbnail || INLINE_MIME_TYPES.has(row.mime_type),
    };
  },

  /** Media / files / audio shared in a conversation, newest first. */
  async gallery(userId, conversationId, { type, before, limit = 60 }) {
    await conversationService.assertParticipant(conversationId, userId);
    const rows = await attachmentRepository.gallery({ conversationId, viewerId: userId, type, before, limit });
    return {
      items: rows.map((row) => ({
        ...toAttachment(row),
        messageId: row.message_id,
        senderId: row.sender_id,
        senderName: row.sender_name ?? null,
        createdAt: new Date(row.message_created_at).toISOString(),
      })),
      hasMore: rows.length === limit,
    };
  },

  /** Remove uploads that were never sent (e.g. the user cancelled or closed the tab). */
  async deleteOrphans() {
    const before = new Date(Date.now() - config.uploads.orphanTtlHours * 3_600_000);
    const rows = await attachmentRepository.listOrphans(before);
    if (rows.length === 0) return 0;
    await attachmentRepository.deleteByIds(rows.map((row) => row.id));
    await attachmentStorage.releaseFiles(rows.flatMap((row) => [row.storage_key, row.thumbnail_key]).filter(Boolean));
    logger.info('Deleted unsent uploads', { count: rows.length });
    return rows.length;
  },
};
